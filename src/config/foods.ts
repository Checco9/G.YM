/**
 * Catalogo alimenti di sistema. Valori medi per 100 g (100 ml per le bevande), carboidrati disponibili
 * come da etichetta europea. Sono valori indicativi: per un prodotto specifico conviene creare
 * un alimento personale con i valori riportati in etichetta.
 * Per modificare un valore basta cambiarlo qui e rilanciare `npm run db:seed`.
 */
export type CatalogFood = {
  slug: string;
  name: string;
  category: string;
  unit: "g" | "ml";
  kcal: number;
  protein: number;
  carbs: number;
  fat: number;
  servingSize?: number;
  servingLabel?: string;
};

type Row = [name: string, kcal: number, protein: number, carbs: number, fat: number, servingSize?: number, servingLabel?: string];

const slugify = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function group(category: string, rows: Row[], unit: "g" | "ml" = "g"): CatalogFood[] {
  return rows.map(([name, kcal, protein, carbs, fat, servingSize, servingLabel]) => ({
    slug: slugify(name) + (unit === "ml" ? "-ml" : ""),
    name,
    category,
    unit,
    kcal,
    protein,
    carbs,
    fat,
    servingSize,
    servingLabel,
  }));
}

